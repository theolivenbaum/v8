using System.Text;

namespace V8Sharp.TestRunner.Results;

/// <summary>
/// A committed list of the tests of one suite that currently do not behave as
/// the suite's <c>.status</c> file expects on one engine:
/// <c>expectations/&lt;suite&gt;.&lt;engine&gt;.txt</c>, one test id per line,
/// sorted, with an optional <c># reason</c>. A run compares against it to
/// report newly failing and newly passing tests.
/// </summary>
public sealed class ExpectationsFile
{
    public string Suite { get; }
    public string Engine { get; }
    public string Path { get; }
    public bool Exists { get; }

    /// <summary>Test id to reason ("" when none).</summary>
    public SortedDictionary<string, string> Failing { get; } = new(StringComparer.Ordinal);

    public ExpectationsFile(string directory, string suite, string engine)
    {
        Suite = suite;
        Engine = engine;
        Path = System.IO.Path.Combine(directory, $"{suite}.{engine}.txt");
        Exists = File.Exists(Path);
        if (!Exists) return;
        foreach (var raw in File.ReadAllLines(Path, Encoding.UTF8))
        {
            string line = raw.Trim();
            if (line.Length == 0 || line.StartsWith('#')) continue;
            int hash = line.IndexOf(" #", StringComparison.Ordinal);
            string id = (hash >= 0 ? line[..hash] : line).Trim();
            string reason = hash >= 0 ? line[(hash + 2)..].Trim() : "";
            Failing[id] = reason;
        }
    }

    /// <summary>
    /// Rewrites the file from a run. <paramref name="ran"/> are the ids that
    /// ran (a filtered run only updates its own entries); <paramref name="failing"/>
    /// maps the ones with unexpected outcomes to an automatic reason. A reason
    /// already in the file is kept while the test keeps failing, so hand-written
    /// explanations survive updates.
    /// </summary>
    public void Update(IReadOnlySet<string> ran, IReadOnlyDictionary<string, string> failing)
    {
        foreach (var id in ran)
        {
            if (failing.TryGetValue(id, out var reason))
            {
                if (!Failing.TryGetValue(id, out var old) || old.Length == 0 || IsAutomatic(old)) Failing[id] = reason;
            }
            else
            {
                Failing.Remove(id);
            }
        }
        var sb = new StringBuilder();
        sb.Append("# ").Append(Suite).Append(" tests whose outcome on the ").Append(Engine)
          .Append(" engine differs from ").Append(Suite).Append(".status.\n");
        sb.Append("# Generated by V8Sharp.TestRunner --update-expectations; one test per line,\n");
        sb.Append("# sorted, with an optional reason after '#'. Hand-written reasons are kept.\n");
        foreach (var (id, reason) in Failing)
        {
            sb.Append(id);
            if (reason.Length > 0) sb.Append("  # ").Append(reason);
            sb.Append('\n');
        }
        Directory.CreateDirectory(System.IO.Path.GetDirectoryName(Path)!);
        File.WriteAllText(Path, sb.ToString(), new UTF8Encoding(false));
    }

    /// <summary>Reasons the runner writes itself: the observed outcome.</summary>
    public static bool IsAutomatic(string reason) => reason is "FAIL" or "CRASH" or "TIMEOUT" or "PASS";
}
