using System.Text;
using System.Text.RegularExpressions;

namespace V8Sharp.TestRunner.Results;

/// <summary>
/// A committed list of the tests of one suite that currently do not behave as
/// the suite's <c>.status</c> file expects on one engine:
/// <c>expectations/&lt;suite&gt;.&lt;engine&gt;.txt</c>, one test id per line,
/// sorted, with an optional <c># reason</c>. A line with <c>*</c> is a glob
/// (<c>**</c> spans directories) that covers a whole class of failures, such
/// as a feature the engine lacks; globs are written by hand and kept as they
/// are. A run compares against the file to report newly failing and newly
/// passing tests.
/// </summary>
public sealed class ExpectationsFile
{
    public string Suite { get; }
    public string Engine { get; }
    public string Path { get; }
    public bool Exists { get; }

    /// <summary>Exact test ids to reason ("" when none).</summary>
    public SortedDictionary<string, string> Failing { get; } = new(StringComparer.Ordinal);

    /// <summary>Glob lines, in file order, with their reason.</summary>
    public List<(string Glob, string Reason, Regex Regex)> Patterns { get; } = [];

    public ExpectationsFile(string directory, string suite, string engine)
    {
        Suite = suite;
        Engine = engine;
        Path = System.IO.Path.Combine(directory, $"{suite}.{engine}.txt");
        Exists = File.Exists(Path);
        if (!Exists) return;
        foreach (var raw in File.ReadAllLines(Path, Encoding.UTF8))
        {
            string line = raw.Trim();
            if (line.Length == 0 || line.StartsWith('#')) continue;
            int hash = line.IndexOf(" #", StringComparison.Ordinal);
            string id = (hash >= 0 ? line[..hash] : line).Trim();
            string reason = hash >= 0 ? line[(hash + 2)..].Trim() : "";
            if (id.Contains('*')) Patterns.Add((id, reason, GlobRegex(id)));
            else Failing[id] = reason;
        }
    }

    static Regex GlobRegex(string glob)
    {
        var sb = new StringBuilder("^");
        for (int i = 0; i < glob.Length; i++)
        {
            char c = glob[i];
            if (c == '*' && i + 1 < glob.Length && glob[i + 1] == '*') { sb.Append(".*"); i++; }
            else if (c == '*') sb.Append("[^/]*");
            else sb.Append(Regex.Escape(c.ToString()));
        }
        return new Regex(sb.Append('$').ToString(), RegexOptions.CultureInvariant);
    }

    /// <summary>The glob that covers <paramref name="id"/>, or null.</summary>
    public string? MatchingPattern(string id)
    {
        foreach (var p in Patterns) if (p.Regex.IsMatch(id)) return p.Glob;
        return null;
    }

    /// <summary>Whether the file expects <paramref name="id"/> to have an unexpected outcome.</summary>
    public bool IsKnownFailure(string id) => Failing.ContainsKey(id) || MatchingPattern(id) is not null;

    /// <summary>
    /// Rewrites the file from a run. <paramref name="ran"/> are the ids that
    /// ran (a filtered run only updates its own entries); <paramref name="failing"/>
    /// maps the ones with unexpected outcomes to an automatic reason (the
    /// outcome). A hand-written reason is kept while its test keeps failing;
    /// failing tests covered by a glob are not listed one by one.
    /// </summary>
    public void Update(IReadOnlySet<string> ran, IReadOnlyDictionary<string, string> failing)
    {
        foreach (var id in ran)
        {
            if (failing.TryGetValue(id, out var reason) && MatchingPattern(id) is null)
            {
                if (!Failing.TryGetValue(id, out var old) || old.Length == 0 || IsAutomatic(old)) Failing[id] = reason;
            }
            else
            {
                Failing.Remove(id);
            }
        }
        var sb = new StringBuilder();
        sb.Append("# ").Append(Suite).Append(" tests whose outcome on the ").Append(Engine)
          .Append(" engine differs from ").Append(Suite).Append(".status.\n");
        sb.Append("# Generated by V8Sharp.TestRunner --update-expectations; one test per line,\n");
        sb.Append("# sorted, with an optional reason after '#'. Hand-written reasons and glob\n");
        sb.Append("# lines (a failure class: '**' spans directories) are kept.\n");
        foreach (var (glob, reason, _) in Patterns)
        {
            sb.Append(glob);
            if (reason.Length > 0) sb.Append("  # ").Append(reason);
            sb.Append('\n');
        }
        foreach (var (id, reason) in Failing)
        {
            sb.Append(id);
            if (reason.Length > 0) sb.Append("  # ").Append(reason);
            sb.Append('\n');
        }
        Directory.CreateDirectory(System.IO.Path.GetDirectoryName(Path)!);
        File.WriteAllText(Path, sb.ToString(), new UTF8Encoding(false));
    }

    /// <summary>Reasons the runner writes itself: the observed outcome.</summary>
    public static bool IsAutomatic(string reason) => reason is "FAIL" or "CRASH" or "TIMEOUT" or "PASS";
}
